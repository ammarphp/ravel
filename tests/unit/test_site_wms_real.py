"""Opt-in real workflow-manager checks on synthetic local work only."""
import os
from pathlib import Path
import subprocess
import tomllib

import pytest

from ravel.workflow import wms_runtime
from site_install_fixture import SOURCE


def _snakemake():
    if not os.environ.get('RAVEL_TEST_SNAKEMAKE'):
        pytest.skip('set RAVEL_TEST_SNAKEMAKE to run real Snakemake')
    argv=wms_runtime.snakemake_argv(explicit=os.environ['RAVEL_TEST_SNAKEMAKE'])
    if not argv:pytest.fail('RAVEL_TEST_SNAKEMAKE must name an executable')
    return argv


def _workflow(tmp_path):
    snake=tmp_path/'Snakefile'
    snake.write_text('rule all:\n    input: "second.txt"\n'
                     'rule first:\n    output: "first.txt"\n    shell: "printf synthetic > {output}"\n'
                     'rule second:\n    input: "first.txt"\n    output: "second.txt"\n    shell: "cat {input} > {output}"\n')
    return snake


def _shim(tmp_path,argv):
    import shlex
    path=tmp_path/'ravel-snakemake'
    path.write_text('#!/bin/sh\nunset PYTHONPATH PYTHONHOME PYTHONSTARTUP\nexport PYTHONNOUSERSITE=1\n'
                    'exec '+shlex.join(argv)+' "$@"\n')
    path.chmod(0o755)
    return path


def test_real_local_workflow_through_isolated_shim(tmp_path):
    argv=_snakemake();snake=_workflow(tmp_path);shim=_shim(tmp_path,argv)
    done=subprocess.run([str(shim),'--snakefile',str(snake),'--directory',str(tmp_path),'--cores','1','--retries','0'],
        env=dict(os.environ,PYTHONPATH='/fake/view'),capture_output=True,text=True,timeout=120)
    assert done.returncode==0,done.stdout+done.stderr
    assert (tmp_path/'first.txt').read_bytes()==(tmp_path/'second.txt').read_bytes()


def test_real_cluster_generic_profile_with_local_scheduler_fakes(tmp_path):
    argv=_snakemake()
    scripts=tomllib.loads((SOURCE/'pyproject.toml').read_text())['project']['scripts']
    assert {'ravel-wms-condor-submit','ravel-wms-condor-status'} <= set(scripts)
    import yaml
    from ravel.workflow.site_profiles import write_profile
    snake=_workflow(tmp_path);shim=_shim(tmp_path,argv)
    profile=Path(write_profile(tmp_path/'profiles', 'htcondor', cores=1)['path'])
    tools=tmp_path/'tools';tools.mkdir()
    # The descriptors generated by the scheduler-profile stream are the contract.
    # Each fake starts only the supplied job script in this temporary directory.
    submit=tools/'condor_submit'
    submit.write_text('#!/bin/sh\nif [ "$1" = -terse ]; then shift; fi\n'
        'descriptor="$1"\njob=$(sed -n "s/^arguments = //p" "$descriptor" | tr -d \'"\')\n'
        '/bin/sh "$job" > "$FAKE_CONDOR_JOB_LOG" 2>&1\n'
        'printf "%s\\n" "$?" > "$FAKE_CONDOR_EXIT"\necho "1.0 - 1.0"\n')
    for name,text in {'condor_q':'exit 0',
                      'condor_history':'read code < "$FAKE_CONDOR_EXIT"; echo "4 $code"',
                      'condor_rm':'exit 0'}.items():
        (tools/name).write_text('#!/bin/sh\n'+text+'\n')
    for path in tools.iterdir():path.chmod(0o755)
    env=dict(os.environ,PATH=str(tools)+':'+os.environ['PATH'],PYTHONPATH='/fake/view',
             FAKE_CONDOR_EXIT=str(tmp_path/'exit'),FAKE_CONDOR_JOB_LOG=str(tmp_path/'job.log'))
    done=subprocess.run([str(shim),'--snakefile',str(snake),'--directory',str(tmp_path),
        '--profile',str(profile),'--jobs','1','--cores','1','--retries','0'],env=env,
        capture_output=True,text=True,timeout=120)
    assert done.returncode==0,done.stdout+done.stderr
    assert (tmp_path/'first.txt').read_bytes()==(tmp_path/'second.txt').read_bytes()
