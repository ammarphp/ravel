"""What the tree ships names no development record, internal label, workstation path, named
benchmark or challenge, and carries no generated attribution line.

The scan covers exactly the export selection. In a source checkout each selected file is read as
the export publishes it (its declared public transformation applied), and the two files the
export writes anew are left to the public tree's own run; a public tree is read as it is. Licence and citation material may name people and projects; nothing else may.
"""
from functools import lru_cache
import hashlib
from pathlib import Path
import re
import sys

import pytest

ROOT = Path(__file__).resolve().parents[2]

# Work-package, change-registry and review labels of the development process, and section
# pointers into its design documents.
INTERNAL_LABEL = re.compile(
    r'(?<![A-Za-z0-9_/.-])(?:LG-\d+[A-Za-z]?\d*F?\d*|M-\d{2}[A-Za-z]?\d*[A-Za-z]?\d*|OR-\d[A-Za-z0-9]*'
    r'|KM-\d+|CX-[A-Z0-9]+|AL-\d+[A-Z]?|CJ-F?\d+|VA-\d+|B\d-\d{2}|ST-ROOT|CR-\d{3}|MV1[a-z]?|MT-GEN'
    r'|V1-[A-Z]{3,}|v1g(?:-\d+)?)(?![A-Za-z0-9_-])'
    r'|\b[A-Z][A-Z0-9]+(?:-[A-Z0-9]+)+[ \t]*(?:§|section[ \t]+\d|S\d+\.\d)'
    r'|\b(?:AI|AL|LG|OR|B\d)[ \t]*§[ \t]*\d'
    r'|\b(?:Fable|Codex|Gemini)[ \t]+F\d+\b')
# The development-record directories, spelled in parts so this file names none of them.
DEVELOPMENT_RECORD = re.compile(r'\b(?:dev-progress|dev-inventory)/|\bdocs/' r'development/|\bresearch-planning/')
WORKSTATION_PATH = re.compile(r'/Us' r'ers/[A-Za-z][^/\s"\'`]*/|/ho' r'me/(?!runner/)[a-z][a-z0-9_-]*/|[A-Za-z]:\\\\?Users\\\\?')
# A comment or header line a file or generator writes to credit itself (a tool or a model) as
# the author: "# Written by ...", "(* name: generated by ... *)", "% Generated by ...".
GENERATED_ATTRIBUTION = re.compile(
    r'(?i)(?:(?:[#%"\'*;]|//|\(\*|<!--)[ \t]*(?:[^\s:]+:?[ \t]+){0,3}|^[ \t]*)(?:written|generated|created|authored|produced)'
    r' by (?:ravel|the ravel\b|claude|codex|anthropic|openai|gpt|an? (?:ai|language model))|co-authored-by:')
# Exact, reasoned exceptions: {public path: reason}.
ATTRIBUTION_ALLOWED = {
    'src/ravel/setup/steps.py': 'recognises the marker that earlier installer versions wrote, so their files stay replaceable',
}
THIS_FILE = 'tests/unit/test_public_tree_content.py'
# Keyed digests (the generality gate's key) of the compacted names of named benchmarks and
# challenges that public material must not carry; the names themselves are not stored.
NAMED_SUITES = {'bc907d9544ec02f04a59', 'd90dc8a8fef572679d2b'}
# Licence and citation material credits people and upstream projects by name.
# The export writes these anew from the selection; a public tree scans the written files.
EXPORT_WRITTEN = {'DIRECTORY.md', 'distribution.json'}
CREDIT_FILES = {'LICENSE', 'NOTICE', 'THIRD-PARTY-NOTICES.md', 'CITATION.cff', 'src/ravel/data/citations/upstream.json'}


def _credit(public):
    name = public.rsplit('/', 1)[-1]
    return public in CREDIT_FILES or name.startswith(('LICENSE', 'COPYING', 'AUTHORS', 'NOTICE'))


@lru_cache(maxsize=1)
def shipped_texts():
    sys.path.insert(0, str(ROOT / 'src'))
    from ravel.evidence_layout import selected_files
    publish = None
    if (ROOT / 'scripts' / 'export_layout.py').is_file():
        sys.path.insert(0, str(ROOT / 'scripts'))
        import export_layout
        transforms = export_layout.load_public_transforms(ROOT)
        publish = lambda source, public: export_layout.public_bytes(ROOT, source, public, transforms)
    texts = {}
    for source, public in selected_files(ROOT):
        if publish and public in EXPORT_WRITTEN:
            continue
        raw = publish(source, public) if publish else (ROOT / source).read_bytes()
        if b'\0' in raw[:8192]:
            continue
        try:
            texts[public] = raw.decode('utf-8')
        except UnicodeDecodeError:
            continue
    return texts


def hits(pattern, skip=lambda public: False):
    found = []
    for public, text in sorted(shipped_texts().items()):
        if public == THIS_FILE or skip(public):
            continue
        for number, line in enumerate(text.splitlines(), 1):
            if pattern.search(line):
                found.append(f'{public}:{number}')
    return found


def _digest(compact):
    return hashlib.blake2b(compact.encode(), digest_size=10, key=b'ravel-generality-v1').hexdigest()


def named_suite_hits(text, digests=NAMED_SUITES):
    words = re.findall(r'[a-z0-9]+', text.lower())
    runs = set(words) | {a + b for a, b in zip(words, words[1:])}
    return {_digest(run) for run in runs} & digests


@pytest.mark.parametrize('pattern,text', [
    (INTERNAL_LABEL, 'the M-13 broker'), (INTERNAL_LABEL, 'owner AL-10R'), (INTERNAL_LABEL, 'see CR-016'), (INTERNAL_LABEL, '(LG-6 seam)'),
    (INTERNAL_LABEL, 'AGENT-INTERFACES §4'), (INTERNAL_LABEL, 'ML-PROTOCOL section 7'), (INTERNAL_LABEL, 'ML-PROTOCOL S8.5'), (INTERNAL_LABEL, 'Fable F2'),
    (DEVELOPMENT_RECORD, 'see dev-progress/x.md'), (DEVELOPMENT_RECORD, 'docs/' 'development/status.md'),
    (WORKSTATION_PATH, '/Us' 'ers/someone/work'), (WORKSTATION_PATH, '/ho' 'me/someone/x'),
    (GENERATED_ATTRIBUTION, '# Written by ravel export-submission'), (GENERATED_ATTRIBUTION, 'Generated by Claude'),
    (GENERATED_ATTRIBUTION, '# launcher written by the RAVEL recipe'), (GENERATED_ATTRIBUTION, '(* m: generated by the RAVEL kit *)'),
])
def test_the_patterns_recognise_each_kind(pattern, text):
    assert pattern.search(text)


@pytest.mark.parametrize('pattern,text', [
    (INTERNAL_LABEL, 'the R2 gate'), (INTERNAL_LABEL, 'trap T2'), (INTERNAL_LABEL, 'G8 census'), (INTERNAL_LABEL, 'P15 dispatch'),
    (INTERNAL_LABEL, 'an M-2 mass'), (WORKSTATION_PATH, '/home/runner/.local/bin/x'),
    (GENERATED_ATTRIBUTION, 'a receipt written by the worker'), (GENERATED_ATTRIBUTION, 'commands are generated by Ravel'),
    (GENERATED_ATTRIBUTION, 'f"{rel} was written by an agent session"'),
])
def test_the_patterns_leave_product_vocabulary_alone(pattern, text):
    assert not pattern.search(text)


def test_named_suite_digests_match_one_word_or_two_adjacent_words():
    from ravel.validation import check_generality
    assert _digest('velvetotter') == check_generality._digest('velvetotter')
    listed = {_digest('velvetotter'), _digest('quarry9')}
    assert named_suite_hits('results on the Velvet Otter dataset', listed)
    assert named_suite_hits('the QUARRY9 suite', listed)
    assert not named_suite_hits('a velvet coat and an otter', listed)
    assert not named_suite_hits('a dijet anomaly search on supplied events')


def test_the_shipped_tree_names_no_internal_label():
    assert hits(INTERNAL_LABEL) == []


def test_the_shipped_tree_points_at_no_development_record():
    assert hits(DEVELOPMENT_RECORD) == []


def test_the_shipped_tree_holds_no_workstation_path():
    assert hits(WORKSTATION_PATH) == []


def test_the_shipped_tree_carries_no_generated_attribution_line():
    assert hits(GENERATED_ATTRIBUTION, skip=lambda public: _credit(public) or public in ATTRIBUTION_ALLOWED) == []


def test_each_attribution_exception_still_names_a_shipped_file_that_needs_it():
    for public in ATTRIBUTION_ALLOWED:
        assert public in shipped_texts() and GENERATED_ATTRIBUTION.search(shipped_texts()[public]), public


def test_the_shipped_tree_names_no_listed_benchmark_or_challenge():
    found = [public for public, text in sorted(shipped_texts().items()) if public != THIS_FILE and named_suite_hits(text)]
    assert found == []
