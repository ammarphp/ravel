"""Typed install steps. Each step is idempotent: it verifies an existing result
before doing work, never overwrites something it did not create, and builds
new trees in a sibling ``.partial-<pid>`` directory that is renamed on success.
"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess

from .fetch import file_digests, safe_extract
from .manifest import expand

OWNED_MARK = "owned by the RAVEL installer"
# Files written by earlier installer versions carry this marker; they stay replaceable.
LEGACY_OWNED_MARKS = ("generated by the RAVEL installer",)


class StepError(RuntimeError):
    """A step failed; the log path explains why."""


class Conflict(StepError):
    """An existing destination differs from the pin; it was left untouched."""


class Deferred(Exception):
    """A manual prerequisite is absent; the step waits for a later run."""


class Runner:
    """Runs external programs. Tests replace it with a recording fake."""

    def run(self, argv, *, cwd=None, env=None, log=None):
        argv = [str(a) for a in argv]
        handle = open(log, "a", encoding="utf-8") if log else subprocess.DEVNULL
        try:
            if log:
                handle.write("$ " + " ".join(argv) + "\n")
                handle.flush()
            result = subprocess.run(argv, cwd=cwd, env=env, stdout=handle, stderr=subprocess.STDOUT,
                                    stdin=subprocess.DEVNULL, check=False)
            return result.returncode
        except OSError as error:
            if log:
                handle.write(f"cannot start {argv[0]}: {error}\n")
            return 127
        finally:
            if log:
                handle.close()

    def capture(self, argv, *, env=None, timeout=30, cwd=None):
        try:
            result = subprocess.run([str(a) for a in argv], capture_output=True, text=True, env=env,
                                    timeout=timeout, check=False, stdin=subprocess.DEVNULL, cwd=cwd)
        except (OSError, subprocess.TimeoutExpired) as error:
            return 127, str(error)
        return result.returncode, (result.stdout or "") + (result.stderr or "")


class Context:
    """Everything a step needs: expanded variables, runner, fetcher and paths."""

    def __init__(self, *, prefix, repo, platform_key, values, runner, fetcher, manifest, catalog,
                 base_env, adopt=False):
        self.prefix, self.repo = Path(prefix), Path(repo)
        self.platform = platform_key
        self.values = values
        self.runner, self.fetcher = runner, fetcher
        self.manifest, self.catalog = manifest, catalog
        self.base_env = base_env
        self.adopt = adopt
        self.log = None

    def env(self, extra=None):
        env = dict(self.base_env)
        for key, value in (extra or {}).items():
            env[key] = expand(value, self.values)
        return env

    def run(self, argv, *, cwd=None, extra_env=None):
        code = self.runner.run(argv, cwd=cwd, env=self.env(extra_env), log=self.log)
        if code != 0:
            raise StepError(f"{Path(str(argv[0])).name} exited with status {code}; see {self.log}")

    def owned_marker(self, kind, name):
        return self.prefix / "state/owned" / f"{kind}-{name}.json"


def subprocess_environment(prefix, values, source=None):
    """A clean child environment: prefix-local caches, no conda/venv activation leakage."""
    env = dict(os.environ if source is None else source)
    for key in ("CONDA_PREFIX", "CONDA_DEFAULT_ENV", "CONDA_SHLVL", "CONDA_EXE", "CONDA_PYTHON_EXE",
                "VIRTUAL_ENV", "PYTHONHOME", "PYTHONPATH", "PIP_REQUIRE_VIRTUALENV", "CONDA_SUBDIR"):
        env.pop(key, None)
    prefix = Path(prefix)
    env.update({
        "RAVEL_NATIVE_BUILD": str(prefix), "RAVEL_NATIVE_BIN": str(prefix / "bin"),
        "CONDA_PKGS_DIRS": str(prefix / "pkgs"), "CONDA_REGISTER_ENVS": "false",
        "CONDA_AUTO_UPDATE_CONDA": "false", "CONDA_NOTIFY_OUTDATED_CONDA": "false",
        "PIP_CACHE_DIR": str(prefix / "cache/pip"), "PIP_DISABLE_PIP_VERSION_CHECK": "1",
        "XDG_CACHE_HOME": str(prefix / "cache"), "PYTHONDONTWRITEBYTECODE": "1",
        "CARGO_HOME": str(prefix / "cache/cargo"), "RUSTUP_HOME": str(prefix / "cache/rustup"),
        "MAKEFLAGS": "-j" + values["JOBS"],
    })
    return env


# ---------------------------------------------------------------- outputs

def outputs(step, values):
    """Paths that must exist for a completed step (explicit plus kind defaults)."""
    declared = [Path(expand(p, values)) for p in step.get("outputs", [])]
    kind = step["kind"]
    if kind in ("git", "archive", "download"):
        declared.append(Path(expand(step["dest"], values)))
    elif kind == "conda_env":
        declared.append(Path(values["ENVS"]) / step["name"] / "conda-meta")
    elif kind == "wrapper":
        declared.append(Path(values["BIN"]) / step["name"])
    elif kind == "miniforge":
        declared.append(Path(values["CONDA"]))
    elif kind in ("write_file", "options_file"):
        declared.append(Path(expand(step["path"], values)))
    return declared


def fingerprint(group_id, step, values, repo, catalog=None):
    """Stable digest of the expanded step and any declared input files."""
    payload = {"group": group_id, "step": expand(step, values)}
    inputs = {}
    for relative in step.get("inputs", []):
        path = Path(repo) / relative
        inputs[relative] = file_digests(path)["sha256"] if path.is_file() else None
    if step["kind"] == "wrapper":
        template = Path(repo) / "native/setup/wrappers" / step["template"]
        inputs["template"] = file_digests(template)["sha256"] if template.is_file() else None
    if step["kind"] == "pdf_sets" and catalog is not None:
        inputs["catalog"] = [[s["name"], s.get("sha256") or s.get("md5")] for s in catalog["sets"]]
    payload["inputs"] = inputs
    raw = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode()
    return hashlib.sha256(raw).hexdigest()


# ---------------------------------------------------------------- step kinds

def _manual(step, ctx):
    probe = step.get("probe")
    if probe:
        argv = expand(probe["argv"], ctx.values)
        code, output = ctx.runner.capture(argv, env=ctx.env())
        if code == 0 and (not probe.get("regex") or re.search(probe["regex"], output)):
            return {"satisfied": True}
    else:
        path = Path(expand(step["path"], ctx.values))
        if path.exists():
            return {"satisfied": True}
    raise Deferred(step["instruction"])


def _miniforge(step, ctx):
    conda = Path(ctx.values["CONDA"])
    root = conda.parent.parent
    if conda.is_file():
        receipt = root / "ravel-bootstrap.sha256"
        return {"reused": str(root), "bootstrap_receipt": receipt.read_text().strip() if receipt.is_file() else None}
    if root.exists():
        raise Conflict(f"{root} exists but has no conda; it was left untouched. Move it aside and rerun.")
    miniforge = ctx.manifest["miniforge"]
    asset = miniforge["assets"][ctx.platform]
    url = miniforge["url"].replace("{asset}", asset["name"])
    installer = ctx.fetcher.fetch(url, asset)
    ctx.run(["bash", str(installer), "-b", "-p", str(root)])
    (root / "ravel-bootstrap.sha256").write_text(f"{asset['sha256']}  {asset['name']}\n")
    return {"installed": str(root), "asset": asset["name"], "sha256": asset["sha256"]}


def _conda_env(step, ctx):
    env_dir = Path(ctx.values["ENVS"]) / step["name"]
    marker = ctx.owned_marker("conda", step["name"])
    if env_dir.exists():
        if marker.is_file():
            # Our own earlier attempt did not finish: set it aside, never delete it.
            trash = ctx.prefix / "trash" / f"{step['name']}-{os.getpid()}"
            trash.parent.mkdir(parents=True, exist_ok=True)
            os.replace(env_dir, trash)
        elif ctx.adopt:
            return {"adopted": str(env_dir)}
        else:
            raise Conflict(f"environment {env_dir} exists and was not created by this installer; "
                           f"it was left untouched (rerun with --adopt to keep it as is)")
    marker.parent.mkdir(parents=True, exist_ok=True)
    marker.write_text(json.dumps({"env": str(env_dir), "pid": os.getpid()}) + "\n")
    conda = ctx.values["CONDA"]
    lock = ctx.repo / "native/setup/locks" / f"{step['name']}-{ctx.values['SUBDIR']}.txt"
    argv = [conda, "create", "--yes", "--quiet", "--prefix", str(env_dir), "--override-channels",
            "--strict-channel-priority", "-c", "conda-forge"]
    argv += ["--file", str(lock)] if lock.is_file() else list(step["specs"])
    ctx.run(argv, extra_env=step.get("env"))
    python = env_dir / "bin/python"
    if step.get("pip"):
        ctx.run([str(python), "-m", "pip", "install", "--no-input", *expand(step["pip"], ctx.values)],
                extra_env=step.get("env"))
    receipt_dir = ctx.prefix / "receipts/conda"
    receipt_dir.mkdir(parents=True, exist_ok=True)
    code, listing = ctx.runner.capture([conda, "list", "--prefix", str(env_dir), "--explicit", "--sha256"],
                                       env=ctx.env(step.get("env")), timeout=120)
    explicit = receipt_dir / f"{step['name']}-{ctx.values['SUBDIR']}.txt"
    if code == 0:
        explicit.write_text(listing)
    marker.unlink(missing_ok=True)
    return {"env": str(env_dir), "lock_used": str(lock) if lock.is_file() else None,
            "explicit_packages": str(explicit) if code == 0 else None}


def _pip(step, ctx):
    python = expand(step["python"], ctx.values)
    requirements = expand(step["requirements"], ctx.values)
    # Build backends found with --no-build-isolation (for example maturin looking for cargo) live beside the interpreter.
    path = os.pathsep.join([str(Path(python).parent), ctx.base_env.get("PATH", "")])
    ctx.run([python, "-m", "pip", "install", "--no-input", *step.get("options", []), *requirements],
            extra_env={"PATH": path})
    return {"python": python, "requirements": requirements}


def _git_head(ctx, path):
    code, output = ctx.runner.capture(["git", "-C", str(path), "rev-parse", "HEAD"], env=ctx.env())
    return output.strip() if code == 0 else None


def _git(step, ctx):
    dest = Path(expand(step["dest"], ctx.values))
    commit = step["commit"]
    if dest.exists():
        head = _git_head(ctx, dest)
        if head == commit:
            code, _ = ctx.runner.capture(["git", "-C", str(dest), "diff", "--quiet", "HEAD"], env=ctx.env())
            if code != 0:
                raise Conflict(f"{dest} is at {commit} but has local changes to tracked files; left untouched")
            return {"verified": str(dest), "commit": commit}
        if ctx.adopt:
            return {"adopted": str(dest), "commit_found": head, "commit_expected": commit, "mismatch": True}
        raise Conflict(f"{dest} exists at {head or 'an unknown revision'}, not the pinned {commit}; "
                       f"it was left untouched")
    partial = dest.with_name(dest.name + f".partial-{os.getpid()}")
    dest.parent.mkdir(parents=True, exist_ok=True)
    _, version = ctx.runner.capture(["git", "--version"], env=ctx.env())
    try:
        ctx.run(["git", "clone", "--no-checkout", "--filter=blob:none", "--quiet", step["url"], str(partial)])
    except StepError as error:
        raise StepError(f"clone failed using {version.strip() or 'git (version unavailable)'}: {error}; "
                        "git 2.19 or newer is required. On macOS rerun with PATH=/usr/bin:$PATH, "
                        "or install a newer git") from error
    code, _ = ctx.runner.capture(["git", "-C", str(partial), "cat-file", "-e", commit + "^{commit}"], env=ctx.env())
    if code != 0:
        ctx.run(["git", "-C", str(partial), "fetch", "--quiet", "origin", commit])
    ctx.run(["git", "-C", str(partial), "-c", "advice.detachedHead=false", "checkout", "--quiet", "--detach", commit])
    head = _git_head(ctx, partial)
    if head != commit:
        raise StepError(f"checkout of {step['url']} gave {head}, not {commit}; kept {partial} for inspection")
    for submodule in step.get("submodules", []):
        ctx.run(["git", "-C", str(partial), "submodule", "update", "--init", "--depth", "1", submodule])
    os.replace(partial, dest)
    return {"cloned": str(dest), "commit": commit, "url": step["url"]}


def _pin(step):
    return {key: step[key] for key in ("sha256", "md5", "size", "blocked_reason") if key in step}


def _archive(step, ctx):
    dest = Path(expand(step["dest"], ctx.values))
    stamp = dest / ".ravel-archive.json"
    digest = step.get("sha256") or step.get("md5")
    if dest.exists():
        if stamp.is_file() and json.loads(stamp.read_text()).get("digest") == digest:
            return {"verified": str(dest)}
        if ctx.adopt:
            return {"adopted": str(dest)}
        raise Conflict(f"{dest} exists but was not extracted from the pinned archive; left untouched")
    archive = ctx.fetcher.fetch(expand(step["url"], ctx.values), _pin(step))
    partial = dest.with_name(dest.name + f".partial-{os.getpid()}")
    dest.parent.mkdir(parents=True, exist_ok=True)
    safe_extract(archive, partial, strip=int(step.get("strip", 0)))
    (partial / ".ravel-archive.json").write_text(json.dumps({"url": step["url"], "digest": digest}) + "\n")
    os.replace(partial, dest)
    return {"extracted": str(dest), "digest": digest}


def _download(step, ctx):
    dest = Path(expand(step["dest"], ctx.values))
    pin = _pin(step)
    if dest.exists():
        actual = file_digests(dest)
        if (pin.get("sha256") and actual["sha256"] == pin["sha256"]) or (pin.get("md5") and actual["md5"] == pin["md5"]):
            return {"verified": str(dest)}
        if ctx.adopt:
            return {"adopted": str(dest)}
        raise Conflict(f"{dest} exists with a different digest; left untouched")
    cached = ctx.fetcher.fetch(expand(step["url"], ctx.values), pin)
    dest.parent.mkdir(parents=True, exist_ok=True)
    partial = dest.with_name(dest.name + f".partial-{os.getpid()}")
    shutil.copyfile(cached, partial)
    os.chmod(partial, int(step.get("mode", "0644"), 8))
    os.replace(partial, dest)
    return {"downloaded": str(dest), "sha256": file_digests(dest)["sha256"]}


def _verify_file(step, ctx):
    path = Path(expand(step["path"], ctx.values))
    if not path.is_file():
        raise StepError(f"expected file is missing: {path}")
    actual = file_digests(path)
    if step.get("sha256") and actual["sha256"] != step["sha256"]:
        raise StepError(f"{path} has sha256 {actual['sha256']}, expected {step['sha256']}")
    return {"verified": str(path), "sha256": actual["sha256"]}


def pdf_set_ready(directory, row):
    info = Path(directory) / (row["name"] + ".info")
    if not info.is_file():
        return False
    text = info.read_text(errors="replace")
    index = re.search(r"^SetIndex:\s*(\d+)", text, re.M)
    members = re.search(r"^NumMembers:\s*(\d+)", text, re.M)
    if not index or int(index.group(1)) != row["lhaid"]:
        return False
    count = int(members.group(1)) if members else 1
    return all((Path(directory) / f"{row['name']}_{i:04d}.dat").is_file() for i in range(count))


def _pdf_sets(step, ctx):
    data = Path(ctx.values["LHAPDF_DATA"])
    data.mkdir(parents=True, exist_ok=True)
    wanted = step.get("sets")
    rows = [r for r in ctx.catalog["sets"] if wanted is None or r["name"] in wanted]
    done = []
    for row in rows:
        dest = data / row["name"]
        if dest.exists():
            if pdf_set_ready(dest, row):
                done.append(row["name"])
                continue
            raise Conflict(f"{dest} exists but is not the complete set with LHAID {row['lhaid']}; left untouched")
        url = ctx.catalog["base_url"].rstrip("/") + "/" + row["name"] + ".tar.gz"
        archive = ctx.fetcher.fetch(url, _pin(row))
        partial = data / f".{row['name']}.partial-{os.getpid()}"
        safe_extract(archive, partial)
        inner = partial / row["name"]
        if not inner.is_dir() or not pdf_set_ready(inner, row):
            raise StepError(f"archive for {row['name']} does not contain a complete set with LHAID {row['lhaid']}; "
                            f"kept {partial}")
        os.replace(inner, dest)
        shutil.rmtree(partial)
        done.append(row["name"])
    source = step.get("index_from")
    copied = []
    if source:
        source = Path(expand(source, ctx.values))
        for name in ("pdfsets.index", "lhapdf.conf"):
            if (source / name).is_file() and not (data / name).exists():
                shutil.copyfile(source / name, data / name)
                copied.append(name)
    return {"sets": done, "index_files": copied, "data_path": str(data)}


def _command(step, ctx):
    unless = step.get("unless")
    if unless:
        code, _ = ctx.runner.capture(expand(unless, ctx.values), env=ctx.env(step.get("env")))
        if code == 0:
            return {"already_satisfied": True}
    argv = expand(step["argv"], ctx.values)
    cwd = expand(step["cwd"], ctx.values) if step.get("cwd") else None
    ctx.run(argv, cwd=cwd, extra_env=step.get("env"))
    missing = [str(p) for p in outputs(step, ctx.values) if not p.exists()]
    if missing:
        raise StepError("command finished but did not produce: " + ", ".join(missing))
    return {"argv": argv}


def engine_is_apptainer(engine):
    name = Path(str(engine)).name
    return "apptainer" in name or "singularity" in name


def _container_pull(step, ctx):
    engine = ctx.values["CONTAINER_ENGINE"]
    reference = f"{step['image']}@{step['digest']}"
    platform = expand(step.get("platform", "{OCI_PLATFORM}"), ctx.values)
    if engine_is_apptainer(engine):
        sif = Path(ctx.values["CONTAINERS"]) / "images" / (step["name"] + ".sif")
        if sif.is_file():
            return {"image": reference, "sif": str(sif), "verified": True}
        sif.parent.mkdir(parents=True, exist_ok=True)
        partial = sif.with_name(sif.name + f".partial-{os.getpid()}")
        ctx.run([engine, "pull", str(partial), "docker://" + reference])
        os.replace(partial, sif)
        return {"image": reference, "sif": str(sif)}
    code, _ = ctx.runner.capture([engine, "image", "inspect", reference], env=ctx.env(), timeout=60)
    if code == 0:
        return {"image": reference, "verified": True}
    ctx.run([engine, "pull", "--platform", platform, reference])
    code, _ = ctx.runner.capture([engine, "image", "inspect", reference], env=ctx.env(), timeout=60)
    if code != 0:
        raise StepError(f"{reference} is not present after the pull")
    return {"image": reference, "platform": platform}


def _container_build(step, ctx):
    entry = ctx.manifest["container_build"]
    values = dict(ctx.values, RECIPE=step["recipe"])
    module = entry["module"]
    check = [ctx.values["HOST_PYTHON"], "-c",
             f"import importlib.util,sys; sys.exit(0 if importlib.util.find_spec({module!r}) else 3)"]
    code, _ = ctx.runner.capture(check, env=ctx.env())
    if code != 0:
        raise Deferred(f"the image builder {module} is not available in this checkout yet; "
                       f"rerun the installer after updating RAVEL")
    argv = [a.replace("{RECIPE}", step["recipe"]) for a in entry["argv"]]
    ctx.run(expand(argv, values), extra_env=step.get("env"))
    return {"recipe": step["recipe"], "argv": expand(argv, values)}


def render_template(text, values):
    def replace(match):
        key = match.group(1)
        if key not in values:
            raise StepError("wrapper template needs a value for @" + key + "@")
        return values[key]
    return re.sub(r"@([A-Z_][A-Z0-9_]*)@", replace, text)


def _wrapper(step, ctx):
    template = ctx.repo / "native/setup/wrappers" / step["template"]
    values = {k: str(v) for k, v in expand(step.get("values", {}), ctx.values).items()}
    values.setdefault("PREFIX", ctx.values["P"])
    values.setdefault("ENGINE", ctx.values["CONTAINER_ENGINE"])
    text = render_template(template.read_text(encoding="utf-8"), values)
    if OWNED_MARK not in text:
        raise StepError(f"wrapper template {template} must contain the line '# {OWNED_MARK}'")
    target = Path(ctx.values["BIN"]) / step["name"]
    if target.exists():
        current = target.read_text(encoding="utf-8", errors="replace")
        if current == text:
            return {"verified": str(target)}
        if not any(mark in current for mark in (OWNED_MARK, *LEGACY_OWNED_MARKS)):
            raise Conflict(f"{target} exists and was not written by this installer; left untouched")
    target.parent.mkdir(parents=True, exist_ok=True)
    partial = target.with_name(target.name + f".partial-{os.getpid()}")
    partial.write_text(text, encoding="utf-8")
    os.chmod(partial, 0o755)
    os.replace(partial, target)
    return {"wrapper": str(target)}


def _options_file(step, ctx):
    path = Path(expand(step["path"], ctx.values))
    values = expand(step["values"], ctx.values)
    if not path.is_file() and step.get("template_from"):
        source = Path(expand(step["template_from"], ctx.values))
        if source.is_file():
            shutil.copyfile(source, path)
    lines = path.read_text(encoding="utf-8").splitlines() if path.is_file() else []
    for key, value in values.items():
        pattern = re.compile(r"^\s*#?\s*" + re.escape(key) + r"\s*=")
        replacement = f"{key} = {value}"
        for index, line in enumerate(lines):
            if pattern.match(line):
                lines[index] = replacement
                break
        else:
            lines.append(replacement)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {"options": str(path), "keys": sorted(values)}


def _hardlink_tree(source, target):
    """Recreate ``source`` at ``target`` with hard links (copies across file systems)."""
    def link(src, dst):
        try:
            os.link(src, dst)
        except OSError:
            shutil.copy2(src, dst)
    shutil.copytree(source, target, copy_function=link, symlinks=False)


def _link_children(step, ctx):
    """Make every set directory of ``source`` available inside ``dest``.

    Hard links keep the files inside each environment (tools that check that
    their data belongs to their own prefix accept them) without using more disk.
    """
    source = Path(expand(step["source"], ctx.values))
    dest = Path(expand(step["dest"], ctx.values))
    dest.mkdir(parents=True, exist_ok=True)
    linked, kept = [], []
    for child in sorted(source.iterdir()) if source.is_dir() else []:
        if not child.is_dir() or child.name.startswith("."):
            continue
        target = dest / child.name
        if target.exists() or target.is_symlink():
            kept.append(child.name)
            continue
        partial = dest / f".{child.name}.partial-{os.getpid()}"
        _hardlink_tree(child, partial)
        os.replace(partial, target)
        linked.append(child.name)
    return {"linked": linked, "kept_existing": kept}


def _write_file(step, ctx):
    path = Path(expand(step["path"], ctx.values))
    content = expand(step["content"], ctx.values)
    if path.exists():
        if step.get("only_if_absent") or path.read_text(encoding="utf-8", errors="replace") == content:
            return {"kept": str(path)}
    path.parent.mkdir(parents=True, exist_ok=True)
    partial = path.with_name(path.name + f".partial-{os.getpid()}")
    partial.write_text(content, encoding="utf-8")
    os.replace(partial, path)
    return {"written": str(path)}


HANDLERS = {
    "manual": _manual, "miniforge": _miniforge, "conda_env": _conda_env, "pip": _pip, "git": _git,
    "archive": _archive, "download": _download, "verify_file": _verify_file, "pdf_sets": _pdf_sets,
    "command": _command, "container_pull": _container_pull, "container_build": _container_build,
    "wrapper": _wrapper, "options_file": _options_file, "link_children": _link_children,
    "write_file": _write_file,
}


def run_step(step, ctx):
    return HANDLERS[step["kind"]](step, ctx)
