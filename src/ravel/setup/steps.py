class StepError(RuntimeError):
    """A step failed; the log path explains why."""


class Conflict(StepError):
    """An existing destination differs from the pin; it was left untouched."""


class Deferred(Exception):
    """A manual prerequisite is absent; the step waits for a later run."""


class Runner:
    """Runs external programs. Tests replace it with a recording fake."""

    def run(self, argv, *, cwd=None, env=None, log=None):
        argv = [str(a) for a in argv]
        handle = open(log, "a", encoding="utf-8") if log else subprocess.DEVNULL
        try:
            if log:
                handle.write("$ " + " ".join(argv) + "\n")
                handle.flush()
            result = subprocess.run(argv, cwd=cwd, env=env, stdout=handle, stderr=subprocess.STDOUT,
                                    stdin=subprocess.DEVNULL, check=False)
            return result.returncode
        except OSError as error:
            if log:
                handle.write(f"cannot start {argv[0]}: {error}\n")
            return 127
        finally:
            if log:
                handle.close()

    def capture(self, argv, *, env=None, timeout=30, cwd=None):
        try:
            result = subprocess.run([str(a) for a in argv], capture_output=True, text=True, env=env,
                                    timeout=timeout, check=False, stdin=subprocess.DEVNULL, cwd=cwd)
        except (OSError, subprocess.TimeoutExpired) as error:
            return 127, str(error)
        return result.returncode, (result.stdout or "") + (result.stderr or "")


class Context:
    """Everything a step needs: expanded variables, runner, fetcher and paths."""

    def __init__(self, *, prefix, repo, platform_key, values, runner, fetcher, manifest, catalog,
                 base_env, adopt=False):
        self.prefix, self.repo = Path(prefix), Path(repo)
        self.platform = platform_key
        self.values = values
        self.runner, self.fetcher = runner, fetcher
        self.manifest, self.catalog = manifest, catalog
        self.base_env = base_env
        self.adopt = adopt
        self.log = None

    def env(self, extra=None):
        env = dict(self.base_env)
        for key, value in (extra or {}).items():
            env[key] = expand(value, self.values)
        return env

    def run(self, argv, *, cwd=None, extra_env=None):
        code = self.runner.run(argv, cwd=cwd, env=self.env(extra_env), log=self.log)
        if code != 0:
            raise StepError(f"{Path(str(argv[0])).name} exited with status {code}; see {self.log}")

    def owned_marker(self, kind, name):
        return self.prefix / "state/owned" / f"{kind}-{name}.json"


def subprocess_environment(prefix, values, source=None):
    """A clean child environment: prefix-local caches, no conda/venv activation leakage."""
    env = dict(os.environ if source is None else source)
    for key in ("CONDA_PREFIX", "CONDA_DEFAULT_ENV", "CONDA_SHLVL", "CONDA_EXE", "CONDA_PYTHON_EXE",
                "VIRTUAL_ENV", "PYTHONHOME", "PYTHONPATH", "PYTHONSTARTUP", "PIP_REQUIRE_VIRTUALENV", "CONDA_SUBDIR"):
        env.pop(key, None)
    prefix = Path(prefix)
    env.update({
        "RAVEL_NATIVE_BUILD": str(prefix), "RAVEL_NATIVE_BIN": str(prefix / "bin"),
        "CONDA_PKGS_DIRS": str(prefix / "pkgs"), "CONDA_REGISTER_ENVS": "false",
        "CONDA_AUTO_UPDATE_CONDA": "false", "CONDA_NOTIFY_OUTDATED_CONDA": "false",
        "PIP_CACHE_DIR": str(prefix / "cache/pip"), "PIP_DISABLE_PIP_VERSION_CHECK": "1",
        "XDG_CACHE_HOME": str(prefix / "cache"), "PYTHONDONTWRITEBYTECODE": "1",
        "PYTHONNOUSERSITE": "1",
        "APPTAINER_CACHEDIR": str(prefix / "cache/apptainer"),
        "APPTAINER_TMPDIR": str(prefix / "tmp/apptainer"),
        "CARGO_HOME": str(prefix / "cache/cargo"), "RUSTUP_HOME": str(prefix / "cache/rustup"),
        "MAKEFLAGS": "-j" + values["JOBS"],
    })
    # macOS container tooling keeps its sockets under TMPDIR, and a prefix path is too long for them.
    if str(values.get("PLATFORM", "")).startswith("linux"):
        env["TMPDIR"] = str(prefix / "tmp")
    return env


# ---------------------------------------------------------------- outputs

def outputs(step, values):
    """Paths that must exist for a completed step (explicit plus kind defaults)."""
    declared = [Path(expand(p, values)) for p in step.get("outputs", [])]
    kind = step["kind"]
    if kind in ("git", "archive", "download"):
        declared.append(Path(expand(step["dest"], values)))
    elif kind == "conda_env":
        declared.append(Path(values["ENVS"]) / step["name"] / "conda-meta")
    elif kind == "wrapper":
        declared.append(Path(values["BIN"]) / step["name"])
    elif kind == "miniforge":
        declared.append(Path(values["CONDA"]))
    elif kind in ("write_file", "options_file"):
        declared.append(Path(expand(step["path"], values)))
    return declared


def fingerprint(group_id, step, values, repo, catalog=None):
    """Stable digest of the expanded step and any declared input files."""
    payload = {"group": group_id, "step": expand(step, values)}
    inputs = {}
    for relative in step.get("inputs", []):
        path = Path(repo) / relative
        inputs[relative] = file_digests(path)["sha256"] if path.is_file() else None
    if step["kind"] == "wrapper":
        template = Path(repo) / "native/setup/wrappers" / step["template"]
        inputs["template"] = file_digests(template)["sha256"] if template.is_file() else None
    if step["kind"] == "pdf_sets" and catalog is not None:
        inputs["catalog"] = [[s["name"], s.get("sha256") or s.get("md5")] for s in catalog["sets"]]
    payload["inputs"] = inputs
    raw = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode()
    return hashlib.sha256(raw).hexdigest()


