def require(condition,message):
    if not condition: raise ValueError(message)


def _primitive(value,depth=0):
    require(depth<=32,'bounded process snapshot depth required')
    if value is None or type(value) in (str,bool,int): return value
    if type(value) is float:
        require(math.isfinite(value),'nonfinite process snapshot'); return value
    if isinstance(value,(list,tuple)):
        require(len(value)<=100000,'bounded process population required')
        return [_primitive(x,depth+1) for x in value]
    if isinstance(value,dict):
        require(len(value)<=10000 and all(type(k) is str for k in value),'literal process snapshot keys required')
        return {k:_primitive(v,depth+1) for k,v in value.items()}
    raise ValueError('unsupported ProcessDefinition snapshot value')


def snapshot(definition):
    """Complete actual public Process fields, excluding the shared model object."""
    require(isinstance(definition,dict),'native ProcessDefinition dictionary required')
    fields={k:v for k,v in definition.items() if k not in ('model','decay_chains')}
    # MG5 PhysicsObject/Process.get accepts only a property name.  The
    # released ProcessDefinition.default_setup always declares decay_chains;
    # do not default a missing native property to an empty observed roster.
    fields['decay_chains']=[snapshot(d) for d in definition.get('decay_chains')]
    return _primitive(fields)


def identity(definition):
    require(type(definition) is dict and type(definition.get('legs')) is list and definition['legs'],
            'complete observed external legs required')
    legs=[]
    for leg in definition['legs']:
        require(type(leg) is dict and type(leg.get('ids')) is list and leg['ids'] and
                all(type(x) is int and x!=0 for x in leg['ids']) and type(leg.get('state')) is bool,
                'complete signed external PDG sets and initial/final state required')
        legs.append({'ids':sorted(set(leg['ids'])),'state':leg['state'],'polarization':leg.get('polarization',[])})
    require(not definition.get('decay_chains'),'decay-chain process syntax is outside ordinary intake')
    return {'legs':legs,**{k:definition.get(k) for k in IDENTITY_FIELDS}}


def _append(journal,row):
    raw=(json.dumps(row,sort_keys=True,allow_nan=False,separators=(',',':'))+'\n').encode()
    current=journal.stat().st_size if journal.exists() else 0
    require(current+len(raw)<=LIMIT,'generation-time observation exceeds 2MiB')
    with journal.open('ab') as stream:
        stream.write(raw);stream.flush();os.fsync(stream.fileno())


def install(switcher,commands,journal,commitment):
    """Observe real methods; never change their arguments, results or model state.

Expected aliases are reconstructed on an isolated shallow parser copy with the
released do_define and extract_process APIs. The original model is read by both
parsers; no amplitudes are generated by the prospective parser.
"""
    require(not Path(journal).exists(),'fresh native process observation required')
    journal=Path(journal);plan=[];prefix=[]
    for row in commands:
        if row.startswith('define '): prefix.append(row)
        else: plan.append((list(prefix),row))
    require(plan and len(plan)<=4096,'bounded full prospective process roster required')
    original={name:getattr(switcher,name) for name in ('do_import','do_generate','do_add')}
    states={};depth={}
    def imported(self,line,*args,**kwargs):
        result=original['do_import'](self,line,*args,**kwargs)
        if line.split()[:1]==['model']:
            states[id(self)]={'initial':copy.deepcopy(self._multiparticles),'index':0,'model':self._curr_model}
            _append(journal,{'kind':'model_loaded','command':'import '+line,'pid':os.getpid(),
                'initial_aliases':_primitive(self._multiparticles),'commitment':commitment})
        return result
    def wrapped(name):
        def operation(self,line,*args,**kwargs):
            relevant=name=='do_generate' or line.split()[:1]==['process']
            nested=depth.get(id(self),0)>0
            if not relevant or nested: return original[name](self,line,*args,**kwargs)
            require(id(self) in states,'model import observation missing before process construction')
            state=states[id(self)];index=state['index'];require(index<len(plan),'unexpected extra native process construction')
            definitions,command=plan[index]
            actual_command=('generate ' if name=='do_generate' else 'add ')+line
            require(actual_command==command,'native process dispatch differs from prospective command')
            proxy=copy.copy(self);proxy.history=[];proxy._multiparticles=copy.deepcopy(state['initial'])
            for row in definitions: proxy.do_define(row.removeprefix('define '),log=False)
            depth[id(self)]=1
            try:
                result=original[name](self,line,*args,**kwargs)
            except BaseException as exc:
                _append(journal,{'kind':'process_error','command':command,'index':index,'pid':os.getpid(),
                    'error':type(exc).__name__,
                    'definitions':[snapshot(d) for d in getattr(self,'_curr_proc_defs',[])], 'commitment':commitment})
                raise
            finally: depth[id(self)]=0
            # NLO do_add may validate/translate the model before constructing
            # its ProcessDefinition. Parse the prospective command only after
            # that source-owned transition, on the isolated alias state.
            proxy._curr_model=self._curr_model
            expected=snapshot(proxy.extract_process(command.removeprefix('generate ').removeprefix('add process ')))
            observed=[snapshot(d) for d in self._curr_proc_defs]
            require(observed,'native returned no actual ProcessDefinition')
            _append(journal,{'kind':'process_constructed','command':command,'index':index,'pid':os.getpid(),
                'expected':expected,'definitions':observed,'latest':observed[-1],
                'commitment':commitment})
            state['index']+=1
            return result
        return operation
    switcher.do_import=imported;switcher.do_generate=wrapped('do_generate');switcher.do_add=wrapped('do_add')
    def restore():
        for name,value in original.items(): setattr(switcher,name,value)
    return restore


def verify(rows,commands,commitment):
    """Recompute actual-versus-prospective identity; no trust in a pass label."""
    require(type(rows) is list and rows,'generation-time process observations missing')
    _primitive(rows)
    require(type(commands) is list and all(type(x) is str for x in commands),'prospective source commands required')
    expected=[x for x in commands if not x.startswith('define ')]
    require(rows[0].get('kind')=='model_loaded' and sum(x.get('kind')=='model_loaded' for x in rows)==1,
            'exactly one initial model/default observation required')
    pid=rows[0].get('pid');require(type(pid) is int and pid>0,'actual observation process identity required')
    require(rows[0].get('command')==commitment['model_import'],'observed imported model differs')
    events=[x for x in rows if x.get('kind')!='model_loaded']
    require(len(events)==len(expected),'complete generation-time process denominator required')
    checks=[]
    for index,(row,command) in enumerate(zip(events,expected)):
        require(row.get('kind')=='process_constructed' and row.get('command')==command and
                type(row.get('index')) is int and row['index']==index,'native process observation missing/failed/reordered')
        require(row.get('pid')==pid and row.get('commitment')==commitment,'native process observation subject differs')
        definitions=row.get('definitions');require(type(definitions) is list and len(definitions)==index+1,'actual complete ProcessDefinition roster required')
        require(all(identity(definitions[i])==checks[i]['observed_identity'] for i in range(index)),
                'previous native process identity changed during later construction')
        require(row.get('latest')==definitions[-1],'latest process does not equal retained actual roster')
        checks.append({'index':index,'command':command,'expected_identity':identity(row['expected']),
                       'observed_identity':identity(row['latest']),
                       'matched':identity(row['expected'])==identity(row['latest'])})
    require(rows[0].get('commitment')==commitment,'initial native observation subject differs')
    return {'schema_version':1,'scope':'native_ProcessDefinition_external_PDG_identity',
        'checks':checks,'matched':all(x['matched'] for x in checks),'pid':pid,
        'physics_validated':False,'amplitudes_independently_validated':False,
        'orders_and_all_process_fields_retained':True,'commitment':commitment}


def read_pinned(path,expected):
    """Consume only bounded regular descriptor bytes carrying the controller pin."""
    path=Path(path).absolute()
    require(not any(x.is_symlink() for x in (path,*path.parents)),'native observer source cannot traverse aliases')
    identity=lambda x:(x.st_dev,x.st_ino,x.st_mode,x.st_size,x.st_mtime_ns,x.st_ctime_ns)
    before=path.stat();require(stat.S_ISREG(before.st_mode) and before.st_size<=LIMIT,'bounded regular observer input required')
    descriptor=os.open(path,os.O_RDONLY|os.O_NOFOLLOW|os.O_NONBLOCK)
    try:
        opened=os.fstat(descriptor);require(stat.S_ISREG(opened.st_mode),'observer descriptor must be regular')
        with os.fdopen(descriptor,'rb',closefd=False) as stream: raw=stream.read(LIMIT+1)
        ending=os.fstat(descriptor)
    finally:os.close(descriptor)
    require(len(raw)<=LIMIT and identity(before)==identity(opened)==identity(ending)==identity(path.stat()),
            'observer input changed during read')
    require(hashlib.sha256(raw).hexdigest()==expected,'observer input digest differs')
    return raw


def _unique(pairs):
    out={}
    for key,value in pairs:
        require(key not in out,'duplicate native observer JSON key');out[key]=value
    return out


def _native_main(argv):
    require(len(argv)==4,'exact native observer arguments required')
    mg,request_file,journal=map(Path,argv[:3]);expected_request=argv[3]
    require(mg.is_absolute() and not any(x.is_symlink() for x in (mg,*mg.parents)),'ordinary copied MG root required')
    for relative,expected in SOURCE_HASHES.items():read_pinned(mg/relative,expected)
    def nonfinite(_x):raise ValueError('nonfinite native observer request')
    request=json.loads(read_pinned(request_file,expected_request),object_pairs_hook=_unique,parse_constant=nonfinite)
    require(set(request)=={'schema_version','commands','build','commitment'} and type(request['schema_version']) is int and
            request['schema_version']==1,'closed native observer request schema1 required')
    script=Path(request['build']['path']);read_pinned(script,request['build']['sha256'])
    require(request['commitment']['build_sha256']==request['build']['sha256'] and
            request['commitment']['observer_sha256']==hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            'native observer code/build commitment differs')
    sys.path.insert(0,str(mg))
    from madgraph.interface.master_interface import Switcher  # ONLY in approved native child.
    restore=install(Switcher,request['commands'],journal,request['commitment'])
    try:
        require(not __debug__,'native observer requires the MG default optimized interpreter')
        sys.argv=[str(mg/'bin/mg5_aMC'),'--nocaffeinate',str(script)]
        runpy.run_path(str(mg/'bin/mg5_aMC'),run_name='__main__')
    finally: restore()


if __name__=='__main__': _native_main(sys.argv[1:])
